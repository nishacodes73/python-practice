# Student Subject Manager

# Create a list of subjects
subjects = ["Python", "Java", "SQL"]

# Display all subjects
print("My subjects:", subjects)

# Add a new subject
subjects.append("HTML")

print("Updated subjects:", subjects)

# Count the subjects
print("Total subjects:", len(subjects))

# Create a tuple of study days
days = ("Monday", "Tuesday", "Wednesday")

# Display the first study day
print("First study day:", days[0])

# Display each subject using a loop
print("Subject by subject:")

for subject in subjects:
    print(subject)